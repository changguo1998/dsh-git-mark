#!/usr/bin/env node
/**
 * Assemble the browser half from its plain-function sources.
 *
 * `lib/client.js` is a hand-authored bundle: no bundler exists in this runtime,
 * so the two source files are concatenated into the loader factory and the same
 * core is also wrapped into ESM for the Node unit tests. Both outputs are
 * generated — edit `src/client/*.js`, then run `node tools/build-client.mjs`.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

/** Sources embedded into both artifacts, in dependency order. */
const CORE = join(root, 'src/client/inject-core.js')
const BINDING = join(root, 'src/client/bind-body.js')

/** Names `src/client/inject-core.js` must provide (unit tests rely on them). */
const CORE_EXPORTS = [
  'parseFileAddress',
  'gitMarkFileAddress',
  'markdownImageUrl',
  'isFenceLine',
  'toggleFence',
  'isBlockLine',
  'isTableLine',
  'isDelimiterRow',
  'markTableRow',
  'mergeTableRow',
  'mergeOldNew',
  'injectMarkdown',
  'injectMarkdownHtml',
]

/** Client services this plugin needs before it may register anything. */
const CLIENT_INJECT = ['slots', 'locale', 'documentPreviews']

/**
 * Read one plain-function source and reject module syntax.
 * @param path - absolute source path.
 * @returns the file text, newline-terminated.
 */
async function readBody(path) {
  const text = await readFile(path, 'utf8')
  for (const [index, line] of text.split('\n').entries()) {
    if (/^\s*(import|export)\s/.test(line)) {
      throw new Error(`${path}:${index + 1}: embedded sources must not use module syntax: ${line.trim()}`)
    }
  }
  return text.endsWith('\n') ? text : `${text}\n`
}

/**
 * Verify the core still declares every function the wrapper exports.
 * @param text - the core source text.
 */
function checkCore(text) {
  const missing = CORE_EXPORTS.filter(name => !new RegExp(`^function ${name}\\(`, 'm').test(text))
  if (missing.length > 0) throw new Error(`src/client/inject-core.js is missing: ${missing.join(', ')}`)
}

/** Turn a file body into a commented section of a generated artifact. */
function section(title, text) {
  const body = text.split('\n').filter((line, index, all) => !(index === all.length - 1 && line === ''))
  return [`// ---- ${title} ----`, ...body, ''].join('\n')
}

const core = await readBody(CORE)
const binding = await readBody(BINDING)
checkCore(core)

const clientArtifact = `// @generated by tools/build-client.mjs — do not edit by hand.
// Browser half of dsh-git-mark: the Markdown document body that inserts change
// marks relative to HEAD, plus the registration of that body and its styles.
window.__ModuleLoader__.load({
  id: 'dsh-git-mark',
  factory(require) {
    const React = require('react')
    const primitives = require('@deepseek-ai/dsh-client-ui-primitives')
    const MarkdownText = primitives.MarkdownText

${section('src/client/inject-core.js', core)}${section('src/client/bind-body.js', binding)}    return {
      inject: ${JSON.stringify(CLIENT_INJECT)},
      apply: applyGitMark,
    }
  },
})
`

const coreModule = `// @generated by tools/build-client.mjs — do not edit by hand.
// ESM mirror of src/client/inject-core.js so the Node unit tests exercise the
// exact code the browser runs.
${section('src/client/inject-core.js', core)}
export { ${CORE_EXPORTS.join(', ')} }
`

await mkdir(join(root, 'lib'), { recursive: true })
await mkdir(join(root, 'src/client'), { recursive: true })
await writeFile(join(root, 'lib/client.js'), clientArtifact, 'utf8')
await writeFile(join(root, 'src/client/inject.mjs'), coreModule, 'utf8')

const bytes = Buffer.byteLength(clientArtifact, 'utf8')
console.log(`lib/client.js         ${bytes} bytes`)
console.log(`src/client/inject.mjs ${Buffer.byteLength(coreModule, 'utf8')} bytes`)
